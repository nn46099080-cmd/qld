중요한 것은 무엇을 사느냐가 아니다. 어떤 생각으로 사느냐가 중요하다. 애플 주식을 사더라도 이유가 "내일 오를 것 같아서"라면 투기다. 반대로 ETF를 사더라도 기업의 성장성과 장기적인 경제 발전을 분석한 결과라면 투자에 가깝다. 상품이 투자와 투기를 나누는 것이 아니다. 사고방식이 나눈다.

가격은 매일 변하지만 가치는 천천히 변한다

주식 시장에 처음 들어온 사람들은 대부분 가격에 집중한다. 오늘 몇 퍼센트 올랐는지, 이번 주에 얼마나 수익이 났는지, 다른 사람들은 어떤 종목을 사고 있는지. 하지만 투자자는 가격보다 가치를 본다.

예를 들어보자. 당신이 서울 강남에 건물 한 채를 가지고 있다고 가정해 보자. 어느 날 누군가 와서 50억 원에 사겠다고 말한다. 다음 날에는 40억 원에 사겠다고 말한다. 그리고 일주일 뒤에는 다시 55억 원에 사겠다고 말한다. 건물 자체는 아무것도 변하지 않았다. 임대료도 그대로다. 입지도 그대로다. 건물 가치도 크게 변하지 않았다. 변한 것은 제안 가격뿐이다.

주식도 마찬가지다. 시장 가격은 매일 움직인다. 그러나 기업의 가치는 그렇게 빨리 변하지 않는다. 투자자는 가치를 본다. 투기꾼은 가격만 본다.

인간은 원래 투기를 좋아한다

투자가 어려운 이유는 인간의 본능 때문이다. 사람들은 천천히 부자가 되는 것을 싫어한다. 연 10% 수익률을 20년 동안 유지하는 이야기는 지루하다. 하지만 한 달 만에 300% 상승한 종목 이야기는 흥미롭다. 그래서 사람들은 자연스럽게 투기로 끌린다.

우리의 뇌는 원래 즉각적인 보상을 선호하도록 설계되어 있다. 오늘 1%를 버는 것보다 내일 100%를 벌 가능성에 더 흥분한다. 문제는 시장이 그런 심리를 끊임없이 이용한다는 점이다.

상승장에서는 누구나 천재처럼 보인다. 어떤 종목을 사도 오른다. 주변 사람들은 돈을 번다. SNS는 수익 인증으로 가득하다. 그 순간 투자자는 자신도 모르게 생각한다. "나만 뒤처지는 것 아닐까?" 바로 그 순간부터 분석은 사라지고 감정이 투자 결정을 지배하기 시작한다.

워런 버핏은 왜 부자가 되었을까

많은 사람들은 워런 버핏이 엄청난 투자 기술을 가지고 있다고 생각한다. 물론 사실이다. 하지만 그의 가장 강력한 무기는 종목 선정 능력이 아니다. 시간이다.

