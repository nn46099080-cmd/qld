투자자의 가장 큰 적

초보 투자자들은 시장을 두려워한다. 폭락을 두려워한다. 경제 위기를 두려워한다. 하지만 시간이 지나면 진짜 적이 누구인지 알게 된다. 투자자의 가장 큰 적은 시장이 아니다. 자기 자신이다. 공포, 탐욕, 조급함, 후회, 질투 — 이 감정들이 수많은 투자자를 시장 밖으로 밀어낸다. 시장은 결국 회복하는 경우가 많다. 그러나 공포에 무너진 투자자는 회복하지 못한다. 그래서 투자의 본질은 종목 선택이 아니다. 심리 관리다.

