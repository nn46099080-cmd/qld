투자와 투기는 완전히 다른 게임이다

대부분의 사람들은 투자와 투기를 비슷한 것으로 생각한다. 주식을 사면 투자이고, 코인을 사면 투기라고 생각하는 사람도 있다. 하지만 나는 전혀 다르게 생각한다. 나는 이 글에서 투자란 다음 세 가지 조건을 만족해야 한다고 말한다.

