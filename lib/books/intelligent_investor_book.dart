닷컴버블이 남긴 교훈

1990년대 후반 미국에서는 인터넷 혁명이 시작되고 있었다. 새로운 기술이 등장했고 세상은 빠르게 변했다. 사람들은 인터넷이 미래라고 믿었다. 그 믿음 자체는 틀리지 않았다. 실제로 인터넷은 세상을 바꾸었다. 문제는 사람들이 미래를 믿은 것이 아니라 가격에 취했다는 점이다.

당시에는 기업 이름에 ".com"만 붙어도 주가가 급등했다. 매출이 없어도, 이익이 없어도, 사업 모델이 없어도 괜찮았다. 사람들은 "어차피 계속 오를 거야"라고 생각했다. 하지만 현실은 달랐다. 2000년 버블이 무너지기 시작했다. 수많은 인터넷 기업들이 사라졌다. 나스닥 지수는 약 80% 가까이 폭락했다. 당시 시장에 처음 들어온 수많은 개인 투자자들이 큰 손실을 입었다. 흥미로운 점은 이들이 바보가 아니었다는 것이다. 오히려 똑똑한 사람도 많았다. 하지만 군중심리를 이기지 못했다. 사람들이 돈을 버는 모습을 보며 뒤늦게 뛰어들었다. 그리고 결국 가장 비싼 가격에 샀다.

금융위기는 또 다른 모습을 보여주었다

2008년 금융위기는 닷컴버블과 반대였다. 이번에는 탐욕이 아니라 공포가 시장을 지배했다. 뉴스에서는 연일 경제 붕괴를 이야기했다. 대형 금융기관이 파산했다. 실업률은 치솟았다. 사람들은 현금을 들고 있어야 안전하다고 생각했다. 당시 많은 투자자들이 "이번에는 정말 다르다"고 말했다. 하지만 역사적으로 시장은 항상 비슷한 말을 들어왔다. 1929년에도, 1973년에도, 1987년에도, 2000년에도, 그리고 2008년에도 그랬다. 공포는 늘 특별해 보인다. 하지만 대부분의 경우 시장은 결국 회복했다. 문제는 많은 투자자들이 회복을 기다리지 못했다는 것이다. 그들은 최악의 시점에 매도했다. 그리고 회복이 시작된 후 다시 비싼 가격에 돌아왔다.

코로나 폭락은 인간 심리를 다시 증명했다

2020년 코로나 팬데믹은 또 하나의 실험이었다. 불과 몇 주 만에 시장은 급락했다. 도시가 봉쇄되고, 공장이 멈추고, 비행기가 멈추고, 경제 활동이 정지되었다. 당시 많은 전문가들은 장기 침체를 예상했다. 그러나 시장은 예상보다 훨씬 빠르게 회복했다. 공포에 매도한 사람들은 충격을 받았다. 그들이 시장 밖에서 기다리는 동안 시장은 다시 상승하기 시작했다. 반면 원칙을 지킨 투자자들은 회복의 수혜를 누렸다. 코로나 폭락은 중요한 사실을 다시 보여주었다. 투자 성공은 미래를 맞추는 능력이 아니라 원칙을 지키는 능력이라는 사실이다.

나의 경고

