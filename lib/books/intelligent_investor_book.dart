인간의 뇌는 투자에 불리하게 설계되어 있다

인간은 원래 투자자가 되도록 진화하지 않았다. 수십만 년 동안 인간은 생존을 위해 즉각적인 위험에 반응해야 했다. 숲속에서 맹수가 나타나면 도망쳐야 했다. 불이 나면 피해야 했다. 위험을 과장해서 인식하는 것이 생존에 유리했다.

